"""Automatically updates the .proto files in this directory."""

import base64
import json
import os
import subprocess

import requests

BASE_URL = 'https://chromium.googlesource.com/chromium/src'
LOG_URL = BASE_URL + '/+log/main/%s?format=JSON&n=1'
TEXT_URL = BASE_URL + '/+/%s/%s?format=TEXT'
GO_PACKAGE = 'option go_package = "infra/tools/result_adapter/proto;%s_pb";'

PROTO_PATHS = [
    'build/util/lib/proto/exception_occurrences.proto',
]


def main():
  """Automatically updates the .proto files from the list."""
  base_dir = os.path.abspath(os.path.dirname(__file__))

  proto_files = []
  for proto_path in PROTO_PATHS:
    resp = requests.get(LOG_URL % (proto_path,))
    commit = str(json.loads(resp.text[4:])['log'][0]['commit'])
    print('Updating %r to %r' % (proto_path, commit))

    content_req = requests.get(TEXT_URL % (commit, proto_path))
    content = base64.b64decode(content_req.text).decode('utf8')

    basename = os.path.basename(proto_path)
    file_path = os.path.join(base_dir, basename)
    with open(file_path, 'w') as fp:
      print('// Generated by update.py. DO NOT EDIT.', file=fp)
      print('// This proto were copied from:', file=fp)
      print('// ' + BASE_URL + '/+/' + commit + '/' + proto_path, file=fp)
      fp.write(content)
      filename, _ = os.path.splitext(basename)
      print('\n' + (GO_PACKAGE % (filename,)), file=fp)
    proto_files.append(file_path)

  # generate go files
  subprocess.check_call([
      'protoc',
      f"-I{base_dir}",
      f"--go_out={os.path.join(base_dir, '../../../..')}",
  ] + proto_files)
  print('Done.')


if __name__ == '__main__':
  main()
